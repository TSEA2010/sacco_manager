"""Kenya Data Protection Act 2019 helpers: a member's data-access export (everything the SACCO
holds about them, as JSON) and consent recording. Financial records are kept, not deleted:
SACCO and AML law require retention."""

import json

import frappe
from frappe import _
from frappe.utils import now_datetime, today

PII = ["name", "member_no", "full_name", "first_name", "middle_name", "last_name", "id_number", "kra_pin", "phone",
	"email_id", "date_of_birth", "gender", "marital_status", "branch", "joining_date", "status", "contact_name",
	"contact_email", "contact_phone", "relation", "consent_data_processing", "consent_date", "consent_method", "sms_opt_out"]


@frappe.whitelist()
def export_member_data(member):
	"""Subject access request: download a JSON file of the member's personal and financial data."""
	frappe.only_for(("SACCO Manager", "SACCO Administrator", "System Manager"))
	m = frappe.db.get_value("SACCO Member", member, PII, as_dict=True)
	if not m:
		frappe.throw(_("Member not found."))
	accounts = frappe.get_all("SACCO Savings Account", filters={"member": member}, fields=["name", "account_type", "balance", "status"])
	data = {
		"generated_at": str(now_datetime()),
		"generated_by": frappe.session.user,
		"member": m,
		"savings_accounts": accounts,
		"savings_transactions": frappe.get_all("SACCO Savings Transaction", filters={"member": member, "docstatus": 1},
			fields=["name", "posting_date", "transaction_type", "amount", "balance_after", "reference_no"], order_by="posting_date"),
		"share_ledger": frappe.get_all("SACCO Share Ledger", filters={"member": member, "docstatus": 1},
			fields=["name", "date", "transaction_type", "shares", "total_amount"], order_by="date"),
		"loans": frappe.get_all("Loan", filters={"applicant": frappe.db.get_value("SACCO Member", member, "customer") or "-", "docstatus": 1},
			fields=["name", "loan_product", "loan_amount", "disbursement_date", "status", "total_principal_paid"]),
		"guarantees_given": frappe.get_all("SACCO Loan Guarantor", filters={"guarantor_member": member},
			fields=["loan_application", "pledge_value", "status"]),
	}
	frappe.get_doc({"doctype": "Comment", "comment_type": "Info", "reference_doctype": "SACCO Member", "reference_name": member,
		"content": _("Data-access export generated by {0}.").format(frappe.session.user)}).insert(ignore_permissions=True)
	frappe.local.response.filename = f"Member data {m.member_no or member} {today()}.json"
	frappe.local.response.filecontent = json.dumps(data, indent=1, default=str)
	frappe.local.response.type = "download"


@frappe.whitelist()
def record_consent(member, method="Signed form"):
	frappe.has_permission("SACCO Member", "write", member, throw=True)
	frappe.db.set_value("SACCO Member", member, {"consent_data_processing": 1, "consent_date": today(), "consent_method": method})
	frappe.get_doc({"doctype": "Comment", "comment_type": "Info", "reference_doctype": "SACCO Member", "reference_name": member,
		"content": _("Data-processing consent recorded ({0}) by {1}.").format(method, frappe.session.user)}).insert(ignore_permissions=True)
	return _("Consent recorded.")
